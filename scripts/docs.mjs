// Generates docs/PRESENTATION_SCRIPT.md and docs/TIMING_AUDIT.md from the
// SLIDES data in src/data/steps.ts, so the documented slide count, word count
// and timing can never drift from the deck. Runs as part of `npm run build`;
// `node scripts/docs.mjs --check` fails if the committed docs are out of date.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bundled = await build({
  entryPoints: [join(root, 'src/data/steps.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
  logLevel: 'silent',
});
const mod = await import('data:text/javascript;base64,' + Buffer.from(bundled.outputFiles[0].text).toString('base64'));
const { SLIDES, STEPS, SECTIONS, PACE } = mod;

const words = (s) => (s.match(/[\p{L}\p{N}][\p{L}\p{N}’'.%,-]*/gu) ?? []).length;
const fmt = (sec) => { const r = Math.round(sec); return `${Math.floor(r / 60)}:${String(r % 60).padStart(2, '0')}`; };

const rows = STEPS.map((st, i) => {
  const s = SLIDES[i];
  const w = st.notes.reduce((a, p) => a + words(p), 0);
  return { n: i + 1, s, st, w, plan: s.cue?.sec ?? 0 };
});
const total = rows.reduce((a, r) => a + r.w, 0);
const seconds = (w, wpm) => (w / wpm) * 60;
const transition = PACE.transitionSeconds * rows.length;
const planned = rows.reduce((a, r) => a + r.plan, 0);

// ── PRESENTATION_SCRIPT.md ──────────────────────────────────────────────────
const script = [
  '# Presentation Script',
  '',
  '<!-- Generated by scripts/docs.mjs from src/data/steps.ts. Do not edit by hand. -->',
  '',
  `**${rows.length} steps · ${total} spoken words · ${fmt(seconds(total, PACE.slowWpm) + transition)} to ${fmt(seconds(total, PACE.fastWpm) + transition)}** with transitions (${PACE.fastWpm} to ${PACE.slowWpm} words per minute, ${PACE.transitionSeconds} s per step).`,
  '',
  'The spoken text is the speaker notes (`N`, or the presenter window). The slide shows a shorter version.',
  '',
];
let clock = 0;
for (const r of rows) {
  script.push(`## ${String(r.n).padStart(2, '0')} · ${r.s.chapter} · ${r.s.title}`);
  script.push('');
  script.push(`*${r.w} words · planned ${fmt(r.plan)} · start by ${fmt(clock)} · on screen: ${r.s.purpose ?? ''}*`);
  script.push('');
  if (r.s.cue) script.push(`> **Show:** ${r.s.cue.demo} **Skip:** ${r.s.cue.skip}`, '');
  for (const p of r.st.notes) script.push(p, '');
  clock += r.plan || seconds(r.w, PACE.midWpm) + PACE.transitionSeconds;
}

// ── TIMING_AUDIT.md ─────────────────────────────────────────────────────────
const timing = [
  '# Timing Audit',
  '',
  '<!-- Generated by scripts/docs.mjs from src/data/steps.ts. Do not edit by hand. -->',
  '',
  `Source of truth: \`src/data/steps.ts\` (${rows.length} steps). "Planned" is the presenter cue for each step, which includes demonstrations and pauses. The spoken estimate is the speaker notes at ${PACE.fastWpm} to ${PACE.slowWpm} words per minute, plus ${PACE.transitionSeconds} s per step.`,
  '',
  '| Section | Steps | Words | Target | Planned | Spoken at 110 wpm | Spoken at 100 wpm |',
  '|---|---|---:|---|---:|---:|---:|',
];
for (const sec of SECTIONS) {
  const rs = rows.filter((r) => r.s.chapter === sec.name);
  if (!rs.length) continue;
  const w = rs.reduce((a, r) => a + r.w, 0);
  const t = PACE.transitionSeconds * rs.length;
  const pl = rs.reduce((a, r) => a + r.plan, 0);
  timing.push(`| ${sec.name} | ${rs[0].n}${rs.length > 1 ? ` to ${rs[rs.length - 1].n}` : ''} | ${w} | ${sec.target} | ${fmt(pl)} | ${fmt(seconds(w, PACE.fastWpm) + t)} | ${fmt(seconds(w, PACE.slowWpm) + t)} |`);
}
timing.push(`| **Total** | **${rows.length}** | **${total}** | **20:00** | **${fmt(planned)}** | **${fmt(seconds(total, PACE.fastWpm) + transition)}** | **${fmt(seconds(total, PACE.slowWpm) + transition)}** |`);
timing.push('', '## Per step', '', '| # | Section | Title | Words | Planned | Start by |', '|---:|---|---|---:|---:|---:|');
clock = 0;
for (const r of rows) {
  timing.push(`| ${r.n} | ${r.s.chapter} | ${r.s.title} | ${r.w} | ${fmt(r.plan)} | ${fmt(clock)} |`);
  clock += r.plan || seconds(r.w, PACE.midWpm) + PACE.transitionSeconds;
}
timing.push('', `Rehearsal checkpoints: the presenter window (\`P\`) shows the same "start by" time and the cue (time, show, skip) for every step.`, '');

const out = { 'docs/PRESENTATION_SCRIPT.md': script.join('\n'), 'docs/TIMING_AUDIT.md': timing.join('\n') };
if (process.argv.includes('--check')) {
  const stale = Object.entries(out).filter(([f, s]) => readFileSync(join(root, f), 'utf8').replace(/\r\n/g, '\n') !== s);
  if (stale.length) {
    console.error('docs out of date: ' + stale.map(([f]) => f).join(', ') + ' (run node scripts/docs.mjs)');
    process.exit(1);
  }
} else {
  for (const [f, s] of Object.entries(out)) writeFileSync(join(root, f), s, 'utf8');
}
console.log(`docs: ${rows.length} steps, ${total} words, spoken ${fmt(seconds(total, PACE.fastWpm) + transition)} to ${fmt(seconds(total, PACE.slowWpm) + transition)}, planned ${fmt(planned)}`);
